#!/usr/bin/env bash
# scripts/dev-setup.sh
# Run this ONCE when you first clone the repo.
# After this, daily dev is just: bun run dev:api + bun run dev:web
#
# Prerequisites:
#   - AWS CLI configured (aws configure) with your access keys
#   - bun installed (https://bun.sh)
#   - psql installed (only needed if you run migrations manually)

set -euo pipefail

REGION="ap-south-1"
RDS_ENDPOINT="asteai-development.cfyeuu6yuuq1.ap-south-1.rds.amazonaws.com"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
API_ENV="$REPO_ROOT/apps/api/.env.local"
WEB_ENV="$REPO_ROOT/apps/web/.env.local"

echo ""
echo "AsteAI - developer setup"
echo "========================"
echo ""

# ── 1. Check prerequisites ────────────────────────────────────────────────────
echo "[ 1/5 ] Checking prerequisites..."

for cmd in aws bun openssl; do
  if ! command -v "$cmd" &>/dev/null; then
    echo "  MISSING: '$cmd'"
    case "$cmd" in
      aws)     echo "  -> https://docs.aws.amazon.com/cli/latest/userguide/install-cliv2.html" ;;
      bun)     echo "  -> curl -fsSL https://bun.sh/install | bash" ;;
      openssl) echo "  -> sudo apt install openssl  OR  brew install openssl" ;;
    esac
    exit 1
  fi
done
echo "  OK: aws, bun, openssl found"

# ── 2. Verify AWS identity ────────────────────────────────────────────────────
echo ""
echo "[ 2/5 ] Verifying AWS credentials..."

if ! aws sts get-caller-identity --region "$REGION" > /dev/null 2>&1; then
  echo "  ERROR: AWS credentials not configured or invalid."
  echo "  Run: aws configure"
  echo "  You need the Access Key ID + Secret from your team lead."
  exit 1
fi

AWS_USER=$(aws sts get-caller-identity --region "$REGION" \
  --query 'Arn' --output text | awk -F'/' '{print $NF}')
echo "  OK: Authenticated as '$AWS_USER'"

# Verify RDS IAM permission
if ! aws rds generate-db-auth-token \
  --hostname "$RDS_ENDPOINT" \
  --port 5432 \
  --username asteai_app \
  --region "$REGION" > /dev/null 2>&1; then
  echo "  ERROR: Cannot generate RDS IAM token."
  echo "  Your IAM user has not been granted access yet."
  echo "  Ask your team lead to add you to infra/terraform.tfvars and run: tofu apply"
  exit 1
fi
echo "  OK: RDS IAM auth working"

# Print their IP so they can send it to the team lead
MY_IP=$(aws ec2 describe-vpcs --region "$REGION" --query 'Vpcs[0].CidrBlock' --output text 2>/dev/null || echo "unknown")
MY_PUBLIC_IP=$(curl -s https://checkip.amazonaws.com 2>/dev/null || echo "unknown")
echo ""
echo "  Your public IP: ${MY_PUBLIC_IP}/32"
echo "  If you can't connect to the DB, send this IP to your team lead"
echo "  so they can add it to infra/terraform.tfvars and run: tofu apply"

# ── 3. Install dependencies ───────────────────────────────────────────────────
echo ""
echo "[ 3/5 ] Installing dependencies..."
cd "$REPO_ROOT"
bun install
echo "  OK: dependencies installed"

# ── 4. Generate .env.local files ─────────────────────────────────────────────
echo ""
echo "[ 4/5 ] Generating .env.local files..."

# Each developer gets their own JWT secrets — totally fine for dev
JWT_SECRET=$(openssl rand -hex 32)
JWT_REFRESH_SECRET=$(openssl rand -hex 32)

cat > "$API_ENV" <<ENV
# Auto-generated by scripts/dev-setup.sh — do not commit
NODE_ENV=development
PORT=3001

DATABASE_HOST=${RDS_ENDPOINT}
DATABASE_PORT=5432
DATABASE_NAME=asteai
DATABASE_USER=asteai_app
DATABASE_PASSWORD=
DATABASE_IAM_AUTH=true
DATABASE_SSL=true
DATABASE_SSL_REJECT_UNAUTHORIZED=false
DATABASE_MAX_POOL=10
DATABASE_IDLE_TIMEOUT_MS=30000

AWS_REGION=${REGION}

JWT_SECRET=${JWT_SECRET}
JWT_EXPIRES_IN=15m
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}
JWT_REFRESH_EXPIRES_IN=7d

CORS_ORIGINS=http://localhost:3000

AI_SERVICE_URL=http://localhost:8000
AI_SERVICE_API_KEY=

RAZORPAY_KEY_ID=
RAZORPAY_KEY_SECRET=
ENV

cat > "$WEB_ENV" <<ENV
# Auto-generated by scripts/dev-setup.sh — do not commit
NEXT_PUBLIC_API_URL=http://localhost:3001
ENV

echo "  OK: apps/api/.env.local written"
echo "  OK: apps/web/.env.local written"

# ── 5. Smoke-test DB connection ───────────────────────────────────────────────
echo ""
echo "[ 5/5 ] Verifying RDS IAM token generation..."

if aws rds generate-db-auth-token \
  --hostname "$RDS_ENDPOINT" --port 5432 \
  --username asteai_app --region "$REGION" > /dev/null 2>&1; then
  echo "  OK: RDS IAM token generated successfully"
else
  echo "  WARN: Could not generate RDS IAM token."
  echo "  The app may not be fully provisioned yet. Ask your team lead to run: cd infra && tofu apply"
fi

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo "========================"
echo "Setup complete!"
echo "========================"
echo ""
echo "Start developing:"
echo ""
echo "  Terminal 1:  bun run dev:api   # NestJS -> http://localhost:3001"
echo "  Terminal 2:  bun run dev:web   # Next.js -> http://localhost:3000"
echo ""
echo "Swagger docs:  http://localhost:3001/api/docs"
echo ""
echo "Connect to DB: ./infra/db-connect.sh"
echo ""
